"""Cookie 策略层测试：两种格式、HttpOnly 前缀、白名单过滤。

这里钉住一个会造成**数据丢失**的坑：curl / 浏览器导出的 cookies.txt 用
`#HttpOnly_` 前缀标记 HttpOnly cookie，而 YouTube 的登录态 cookie
（SID / HSID / SSID / APISID / SAPISID / __Secure-1PSID / __Secure-3PSID）
**全部是 HttpOnly**。

早期实现把所有以 `#` 开头的行当注释丢掉，于是：
1. 用户粘贴的正确 cookies.txt 被过滤成只剩 PREF 之类的非登录 cookie；
2. 更糟的是 `CookieConfigManager.get()` 发现 `filtered != stored` 会**回写文件**，
   等于第一次读取就把磁盘上的登录 cookie 永久删了；
3. 用户看到「保存成功」，但 YouTube 一直是游客态。

所以这组测试的两个重点：HttpOnly 行必须保留、过滤必须幂等。
"""

import importlib.util
import pathlib
import sys
import types
import unittest

ROOT = pathlib.Path(__file__).resolve().parents[1]

if "app" not in sys.modules:
    app_pkg = types.ModuleType("app")
    app_pkg.__path__ = [str(ROOT / "app")]
    sys.modules["app"] = app_pkg


def _load(name: str, relative: str):
    spec = importlib.util.spec_from_file_location(name, ROOT / relative)
    if spec is None or spec.loader is None:
        raise ImportError(f"{relative} spec not found")
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


policy = _load("app.services.cookie_policy", "app/services/cookie_policy.py")

# 一段真实形状的 YouTube cookies.txt（HttpOnly 的都是登录态）
YOUTUBE_COOKIES = (
    "# Netscape HTTP Cookie File\n"
    "# This file was generated by a browser extension\n"
    "#HttpOnly_.youtube.com\tTRUE\t/\tTRUE\t1800000000\tSID\tsecret_sid\n"
    "#HttpOnly_.youtube.com\tTRUE\t/\tTRUE\t1800000000\tHSID\tsecret_hsid\n"
    "#HttpOnly_.youtube.com\tTRUE\t/\tTRUE\t1800000000\tSSID\tsecret_ssid\n"
    "#HttpOnly_.youtube.com\tTRUE\t/\tTRUE\t1800000000\tAPISID\tsecret_apisid\n"
    "#HttpOnly_.youtube.com\tTRUE\t/\tTRUE\t1800000000\tSAPISID\tsecret_sapisid\n"
    "#HttpOnly_.youtube.com\tTRUE\t/\tTRUE\t1800000000\t__Secure-3PSID\tsecret_psid\n"
    ".youtube.com\tTRUE\t/\tFALSE\t1800000000\tPREF\ttz=Asia/Shanghai\n"
    ".youtube.com\tTRUE\t/\tFALSE\t1800000000\tVISITOR_INFO1_LIVE\tvisitor\n"
)

LOGIN_COOKIE_NAMES = ("SID", "HSID", "SSID", "APISID", "SAPISID", "__Secure-3PSID")


class TestYoutubeNetscapeCookies(unittest.TestCase):
    def test_httponly_login_cookies_are_preserved(self):
        filtered = policy.filter_downloader_cookies("youtube", YOUTUBE_COOKIES)
        for name in LOGIN_COOKIE_NAMES:
            with self.subTest(cookie=name):
                self.assertIn(f"\t{name}\t", filtered, f"{name} 是登录态 cookie，不能被丢")

    def test_httponly_prefix_survives_roundtrip(self):
        filtered = policy.filter_downloader_cookies("youtube", YOUTUBE_COOKIES)
        self.assertIn("#HttpOnly_.youtube.com\tTRUE\t/\tTRUE", filtered)

    def test_plain_comments_are_dropped(self):
        filtered = policy.filter_downloader_cookies("youtube", YOUTUBE_COOKIES)
        self.assertNotIn("browser extension", filtered)
        # 但仍然要有一行标准头，yt-dlp 靠它识别格式
        self.assertTrue(filtered.startswith("# Netscape HTTP Cookie File"))

    def test_entry_count_includes_httponly_lines(self):
        filtered = policy.filter_downloader_cookies("youtube", YOUTUBE_COOKIES)
        # 6 个 HttpOnly + PREF + VISITOR_INFO1_LIVE
        self.assertEqual(policy.cookie_entry_count("youtube", filtered), 8)

    def test_filter_is_idempotent(self):
        """幂等很重要：CookieConfigManager.get() 在 filtered != stored 时会回写磁盘。

        不幂等 = 每次读取都改写文件，而且可能逐步丢数据。
        """
        once = policy.filter_downloader_cookies("youtube", YOUTUBE_COOKIES)
        twice = policy.filter_downloader_cookies("youtube", once)
        self.assertEqual(once, twice)

    def test_rejects_header_style_cookie(self):
        with self.assertRaises(ValueError):
            policy.filter_downloader_cookies("youtube", "SID=abc; PREF=xyz")

    def test_rejects_malformed_field_count(self):
        with self.assertRaises(ValueError):
            policy.filter_downloader_cookies(
                "youtube", ".youtube.com\tTRUE\t/\tSID\tvalue\n"
            )

    def test_rejects_oversized_input(self):
        huge = ".youtube.com\tTRUE\t/\tFALSE\t0\tBIG\t" + "x" * (policy.NETSCAPE_MAX_LENGTH + 1)
        with self.assertRaises(ValueError):
            policy.filter_downloader_cookies("youtube", huge)

    def test_empty_input_returns_empty(self):
        self.assertEqual(policy.filter_downloader_cookies("youtube", ""), "")
        self.assertEqual(policy.filter_downloader_cookies("youtube", None), "")

    def test_duplicate_cookies_collapsed(self):
        duplicated = (
            "#HttpOnly_.youtube.com\tTRUE\t/\tTRUE\t1800000000\tSID\tfirst\n"
            "#HttpOnly_.youtube.com\tTRUE\t/\tTRUE\t1800000000\tSID\tsecond\n"
        )
        filtered = policy.filter_downloader_cookies("youtube", duplicated)
        self.assertIn("first", filtered)
        self.assertNotIn("second", filtered)
        self.assertEqual(policy.cookie_entry_count("youtube", filtered), 1)


class TestHeaderFormatCookies(unittest.TestCase):
    def test_bilibili_whitelist_and_order(self):
        filtered = policy.filter_downloader_cookies(
            "bilibili",
            "tracking=remove; bili_jct=csrf; SESSDATA=secret; DedeUserID=42",
        )
        # 输出顺序跟随白名单定义，便于稳定 diff
        self.assertEqual(filtered, "SESSDATA=secret; bili_jct=csrf; DedeUserID=42")

    def test_douyin_keeps_uifid_but_drops_dynamic_mstoken(self):
        """抖音 Argus 风控需要 uifid（来自 UIFID_TEMP / UIFID）。

        历史白名单缺这两项，导致浏览器一键同步过来的有效身份被过滤掉，
        表现是「同步成功但没生效」。而 msToken 每次请求动态生成，必须丢弃。
        """
        filtered = policy.filter_downloader_cookies(
            "douyin",
            "sessionid=auth; UIFID_TEMP=temp123; UIFID=fid456; msToken=dynamic; analytics=remove",
        )
        self.assertIn("UIFID_TEMP=temp123", filtered)
        self.assertIn("UIFID=fid456", filtered)
        self.assertIn("sessionid=auth", filtered)
        self.assertNotIn("msToken", filtered)
        self.assertNotIn("analytics", filtered)

    def test_unknown_platform_rejected(self):
        with self.assertRaises(ValueError):
            policy.filter_downloader_cookies("twitter", "a=b")

    def test_format_lookup(self):
        self.assertEqual(policy.cookie_format("bilibili"), policy.COOKIE_FORMAT_HEADER)
        self.assertEqual(policy.cookie_format("youtube"), policy.COOKIE_FORMAT_NETSCAPE)


class TestCookieHints(unittest.TestCase):
    def test_netscape_platform_hint(self):
        self.assertIn("Netscape", policy.cookie_hint_for_empty("youtube"))

    def test_header_platform_hint(self):
        self.assertIn("登录项", policy.cookie_hint_for_empty("bilibili"))


if __name__ == "__main__":
    unittest.main()
